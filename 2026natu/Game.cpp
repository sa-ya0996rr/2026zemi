// ==================================================
// ゲーム情報
// ==================================================

int turn = 0;

int score = 0;

bool gameOver = false;


// ==================================================
// ゲーム状態
//
// 0 = プレイヤー操作
// 1 = 重力で落下
// 2 = 新しいブロックが出てくる
// ==================================================

int gameState = 0;


// ==================================================
// アニメーション速度
// ==================================================

const float FALL_SPEED = 4.0f;

const float NEW_BLOCK_SPEED = 2.0f;


// ==================================================
// 好物を出す
// ==================================================

void MakeFavoriteFood()
{
    // ------------------------------------------
    // 3ターン終了するまでは出さない
    // ------------------------------------------

    if (turn < 3)
    {
        return;
    }


    // ------------------------------------------
    // ランダムなタイミング
    // 5回に1回くらい
    // ------------------------------------------

    if (rand() % 5 != 0)
    {
        return;
    }


    // ------------------------------------------
    // 羊か牛
    // ------------------------------------------

    int animal = rand() % 2;

    char food;


    if (animal == 0)
    {
        // 羊の好物
        food = 'W';
    }
    else
    {
        // 牛の好物
        food = 'T';
    }


    // ------------------------------------------
    // ランダムな横位置
    // ------------------------------------------

    int x = rand() % WIDTH;


    // ------------------------------------------
    // 好物は1マス
    // ------------------------------------------

    AddBlock(
        food,
        x,
        HEIGHT - 1,
        1);


    int number =
        blockCount - 1;


    // ------------------------------------------
    // 画面の下から出現
    // ------------------------------------------

    blockDrawY[number] =
        (float)(
            BOARD_Y +
            HEIGHT * CELL
            );


    newBlockRising = true;
}


// ==================================================
// 好物判定
// ==================================================

void CheckFavoriteFood()
{
    for (int i = 0;
        i < blockCount;
        i++)
    {
        if (blockExist[i] == false)
        {
            continue;
        }


        // --------------------------------------
        // 好物以外は無視
        // --------------------------------------

        if (blockType[i] != 'W' &&
            blockType[i] != 'T')
        {
            continue;
        }


        for (int j = 0;
            j < blockCount;
            j++)
        {
            if (i == j)
            {
                continue;
            }


            if (blockExist[j] == false)
            {
                continue;
            }


            // ==================================
            // 小麦 → 羊
            // ==================================

            if (blockType[i] == 'W' &&
                blockType[j] == 'S')
            {
                if (blockY[i] + 1 ==
                    blockY[j])
                {
                    if (IsOverlapping(
                        blockX[i],
                        blockLength[i],
                        blockX[j],
                        blockLength[j]))
                    {
                        score += 100;

                        blockExist[i] = false;
                    }
                }
            }


            // ==================================
            // とうもろこし → 牛
            // ==================================

            if (blockType[i] == 'T' &&
                blockType[j] == 'C')
            {
                if (blockY[i] + 1 ==
                    blockY[j])
                {
                    if (IsOverlapping(
                        blockX[i],
                        blockLength[i],
                        blockX[j],
                        blockLength[j]))
                    {
                        score += 100;

                        blockExist[i] = false;
                    }
                }
            }
        }
    }
}


// ==================================================
// 新しい動物を追加
// ==================================================

void AddNewAnimal()
{
    // ------------------------------------------
    // 羊か牛をランダム
    // ------------------------------------------

    int randomAnimal =
        rand() % 2;

    char animal;


    if (randomAnimal == 0)
    {
        animal = 'S';
    }
    else
    {
        animal = 'C';
    }


    // ------------------------------------------
    // 1～4マス
    // ------------------------------------------

    int length =
        rand() % 4 + 1;


    // ------------------------------------------
    // 横位置
    // ------------------------------------------

    int x =
        rand() %
        (WIDTH - length + 1);


    // ------------------------------------------
    // 下から追加
    // ------------------------------------------

    AddBlock(
        animal,
        x,
        HEIGHT - 1,
        length);


    int number =
        blockCount - 1;


    // ------------------------------------------
    // 画面の下からスタート
    // ------------------------------------------

    blockDrawY[number] =
        (float)(
            BOARD_Y +
            HEIGHT * CELL
            );


    newBlockRising = true;
}


// ==================================================
// 重力開始
// ==================================================

void StartGravity()
{
    bool anyFalling = false;


    // ------------------------------------------
    // 全ブロックの落下状態をリセット
    // ------------------------------------------

    for (int i = 0;
        i < blockCount;
        i++)
    {
        if (blockExist[i] == false)
        {
            continue;
        }


        falling[i] = false;
    }


    // ------------------------------------------
    // 落ちるブロックを探す
    // ------------------------------------------

    for (int i = 0;
        i < blockCount;
        i++)
    {
        if (blockExist[i] == false)
        {
            continue;
        }


        // 一番下なら落ちない
        if (blockY[i] >= HEIGHT - 1)
        {
            continue;
        }


        // 支えがなければ落ちる
        if (HasSupport(i) == false)
        {
            falling[i] = true;

            anyFalling = true;
        }
    }


    // ------------------------------------------
    // 落ちるブロックがある
    // ------------------------------------------

    if (anyFalling)
    {
        gameState = 1;

        return;
    }


    // ------------------------------------------
    // すでに全部止まっている
    //
    // ★ここで新しいブロックへ
    // ------------------------------------------

    StartNewBlock();
}


// ==================================================
// 重力による落下
// ==================================================

void UpdateFalling()
{
    bool stillFalling = false;


    // ------------------------------------------
    // 落下アニメーション
    // ------------------------------------------

    for (int i = 0;
        i < blockCount;
        i++)
    {
        if (blockExist[i] == false)
        {
            continue;
        }


        if (falling[i] == false)
        {
            continue;
        }


        // --------------------------------------
        // 次のマスの位置
        // --------------------------------------

        float targetY =
            (float)(
                BOARD_Y +
                (blockY[i] + 1) * CELL
                );


        // --------------------------------------
        // ゆっくり落とす
        // --------------------------------------

        blockDrawY[i] +=
            FALL_SPEED;


        // --------------------------------------
        // まだ途中
        // --------------------------------------

        if (blockDrawY[i] <
            targetY)
        {
            stillFalling = true;

            continue;
        }


        // --------------------------------------
        // 1マス落ちた
        // --------------------------------------

        blockDrawY[i] =
            targetY;


        blockY[i]++;


        falling[i] = false;
    }


    // ------------------------------------------
    // まだ落下中
    // ------------------------------------------

    if (stillFalling)
    {
        return;
    }


    // ------------------------------------------
    // もう一度支えを確認
    // ------------------------------------------

    bool anotherFalling = false;


    for (int i = 0;
        i < blockCount;
        i++)
    {
        if (blockExist[i] == false)
        {
            continue;
        }


        // 一番下
        if (blockY[i] >= HEIGHT - 1)
        {
            falling[i] = false;

            continue;
        }


        // 支えがなければ落ちる
        if (HasSupport(i) == false)
        {
            falling[i] = true;

            anotherFalling = true;
        }
        else
        {
            falling[i] = false;
        }
    }


    // ------------------------------------------
    // まだ落ちるブロックがある
    // ------------------------------------------

    if (anotherFalling)
    {
        gameState = 1;

        return;
    }


    // ------------------------------------------
    // ★全部のブロックが完全に停止
    //
    // ここで初めて新しいブロック
    // ------------------------------------------

    StartNewBlock();
}


// ==================================================
// 新しいブロックを出す
// ==================================================

void StartNewBlock()
{
    // ------------------------------------------
    // ★ここで初めて追加する
    // ------------------------------------------

    AddNewAnimal();


    // ------------------------------------------
    // 新しいブロック出現状態
    // ------------------------------------------

    gameState = 2;
}


// ==================================================
// 新しいブロックが下から出てくる
// ==================================================

void UpdateNewBlock()
{
    if (blockCount <= 0)
    {
        gameState = 0;

        playerMoved = false;

        return;
    }


    // ------------------------------------------
    // 最後に追加されたブロック
    // ------------------------------------------

    int number =
        blockCount - 1;


    if (blockExist[number] == false)
    {
        gameState = 0;

        playerMoved = false;

        return;
    }


    // ------------------------------------------
    // 本来の位置
    // ------------------------------------------

    float targetY =
        (float)(
            BOARD_Y +
            blockY[number] * CELL
            );


    // ------------------------------------------
    // 下からゆっくり上がる
    // ------------------------------------------

    blockDrawY[number] -=
        NEW_BLOCK_SPEED;


    // ------------------------------------------
    // 所定の位置に到着
    // ------------------------------------------

    if (blockDrawY[number] <=
        targetY)
    {
        blockDrawY[number] =
            targetY;


        newBlockRising =
            false;


        // --------------------------------------
        // 好物を出す
        // --------------------------------------

        MakeFavoriteFood();


        // --------------------------------------
        // 次のターン
        // --------------------------------------

        gameState = 0;

        playerMoved = false;
    }
}


// ==================================================
// ゲーム初期化
// ==================================================

void InitGame()
{
    srand(
        (unsigned int)
        time(NULL));


    // ------------------------------------------
    // 初期化
    // ------------------------------------------

    blockCount = 0;

    turn = 0;

    score = 0;

    gameOver = false;

    gameState = 0;


    playerMoved = false;

    playerTurnFinished = false;


    dragging = false;

    dragBlock = -1;


    newBlockRising = false;


    // ------------------------------------------
    // 最初のブロック
    // ------------------------------------------

    MakeInitialBlocks();
}


// ==================================================
// ゲーム更新
// ==================================================

void UpdateGame()
{
    // ------------------------------------------
    // ゲームオーバー
    // ------------------------------------------

    if (gameOver)
    {
        return;
    }


    // ==========================================
    // ① プレイヤー操作
    // ==========================================

    if (gameState == 0)
    {
        UpdatePlayer();


        // --------------------------------------
        // 実際にブロックを動かした
        // --------------------------------------

        if (playerTurnFinished)
        {
            playerTurnFinished =
                false;


            // ターンを進める
            turn++;


            // ----------------------------------
            // 好物判定
            // ----------------------------------

            CheckFavoriteFood();


            // ==================================
            // ★ここが一番重要
            //
            // 動かす
            // ↓
            // 重力
            // ==================================

            StartGravity();
        }


        return;
    }


    // ==========================================
    // ② 重力
    // ==========================================

    if (gameState == 1)
    {
        UpdateFalling();

        return;
    }


    // ==========================================
    // ③ 新しいブロック
    // ==========================================

    if (gameState == 2)
    {
        UpdateNewBlock();

        return;
    }
}


// ==================================================
// 描画
// ==================================================

void DrawGame()
{
    DrawGameScreen(
        turn,
        score,
        gameOver);
}