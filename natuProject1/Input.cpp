#include "Input.h"

#include <DxLib.h>


// =========================================
// コンストラクタ
// =========================================

Input::Input()
{

    for (int i = 0; i < 256; i++)
    {
        key[i] = 0;
    }

}



// =========================================
// 更新
// =========================================

void Input::Update()
{

    GetHitKeyStateAll(key);

}



// =========================================
// 右移動
// =========================================

bool Input::Right()
{

    return key[KEY_INPUT_RIGHT];

}



// =========================================
// 左移動
// =========================================

bool Input::Left()
{

    return key[KEY_INPUT_LEFT];

}



// =========================================
// ジャンプ
// =========================================

bool Input::Jump()
{

    return key[KEY_INPUT_SPACE];

}



// =========================================
// ESC
// =========================================

bool Input::Escape()
{

    return key[KEY_INPUT_ESCAPE];

}